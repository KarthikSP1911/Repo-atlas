/**
 * ARCHITECTURE.md draft for `export_guide`, plus the stateless confirm token.
 *
 * The draft is a pure function of the snapshot, so the same snapshot always gives the same text.
 * The token is HMAC-SHA256(secret, snapshotId | sha256(draft) | expiry): it needs no storage,
 * survives restarts, and is bound to the exact draft that was previewed. Text from the repo is
 * untrusted: it is flattened to one line, stripped of markup and quoted, never rendered as
 * headings, links, HTML or instructions.
 */

export const TOKEN_TTL_MS = 10 * 60 * 1000;
export const MIN_SECRET_LENGTH = 16;

// --- Safe text -----------------------------------------------------------------------

/** One line of untrusted text, safe inside a markdown table cell or a blockquote. */
export function safeText(text: string | undefined, max = 200): string {
  if (!text) return '';
  return text
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/<[^>]*>/g, '')
    .replace(/\b(?:https?|ftp|file):\/\/\S+/gi, 'link removed') // bare URLs would be auto-linked by renderers
    .replace(/\b(?:javascript|vbscript|data)\s*:/gi, '')
    .replace(/[`*_~#>\[\]()!|\\]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, max);
}

/** A repo path or name inside inline code. Backticks cannot appear in it. */
const code = (p: string): string => `\`${p.replace(/`/g, "'").replace(/[\r\n]/g, '')}\``;

// --- Draft ---------------------------------------------------------------------------

export function renderArchitecture(idx: GraphIndex): string {
  const o = overviewOf(idx);
  const lim = limitsOf(idx.snap);
  const out: string[] = [];
  // The heading only ever holds a plain name; anything else falls back to the validated repo name.
  const name = o.name && /^[A-Za-z0-9@._/ -]{1,60}$/.test(o.name) ? o.name : idx.repo.split('/')[1];

  // Facts used by several sections, worked out once.
  const allFiles = [...idx.files.values()];
  const entries = normalizedEntries(idx).slice(0, 5);
  const core = allFiles
    .filter((f) => (f.meta.fanIn ?? 0) > 0 && !f.meta.isTest)
    .sort((a, b) => (b.meta.fanIn ?? 0) - (a.meta.fanIn ?? 0) || a.path.localeCompare(b.path))
    .slice(0, 6);
  const testFiles = allFiles.filter((f) => f.meta.isTest).length;
  const coreWithTests = core.filter((f) => (f.meta.testedBy ?? []).length > 0);
  const owned = new Map<string, number>();
  for (const f of allFiles) for (const own of f.meta.owners ?? []) owned.set(own, (owned.get(own) ?? 0) + 1);
  const top = [...owned.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 5);
  const keys = rankKeyFiles(idx, 'new_dev', 8).tiers.mustRead.slice(0, 8);
  const layout = folderRoles(idx);
  const languages = Object.entries(o.languages).sort((a, b) => b[1] - a[1]);
  const sourceFiles = allFiles.filter((f) => !f.meta.isTest).length;

  out.push(`# ${name} architecture (draft)`, '');
  out.push(`> Draft generated by RepoAtlas from snapshot ${code(idx.id)} (commit ${code(idx.snap.sha.slice(0, 7))}, built ${lim.asOf}).`);
  out.push('> It comes from static analysis and git history, not from running the code. Check every claim before committing it.', '');

  out.push('## Overview', '');
  if (o.description) out.push(`> ${safeText(o.description, 300)}`, '');
  out.push(`- Repository: ${code(idx.repo)}${o.license ? `, licence ${safeText(o.license, 40)}` : ''}`);
  if (Object.keys(o.languages).length) out.push(`- Languages (file counts): ${Object.entries(o.languages).sort((a, b) => b[1] - a[1]).slice(0, 6).map(([l, n]) => `${safeText(l, 20)} ${n}`).join(', ')}`);
  if (o.stack.length) out.push(`- Stack (from dependencies): ${o.stack.map((s) => safeText(s, 30)).join(', ')}`);
  if (o.packageManager) out.push(`- Package manager: ${safeText(o.packageManager, 30)}`);
  if (o.workspaces.length) out.push(`- Workspaces: ${o.workspaces.map((w) => code(safeText(w, 60))).join(', ')}`);
  out.push('');

  out.push('## At a glance', '');
  const kind = entries.length === 0 ? 'a library (nothing in it starts on its own; other code imports it)' : `a program with ${entries.length} entry point${entries.length === 1 ? '' : 's'} (files that start running on their own)`;
  out.push(`- What it is: ${kind}${languages[0] ? `, mostly ${safeText(languages[0][0], 20)}` : ''}, ${sourceFiles} source files in ${layout.length} top-level folder${layout.length === 1 ? '' : 's'}.`);
  const stepOf = (s: string): string | undefined => o.runSteps.find((r) => r.step === s)?.command;
  const how = [['install', stepOf('install')], ['build', stepOf('build')], ['test', stepOf('test')]].filter((x): x is [string, string] => !!x[1]);
  out.push(how.length ? `- How to run it: ${how.map(([s, c]) => `${s} with ${code(safeText(c, 60))}`).join(', ')}.` : '- How to run it: no install, build or test command could be derived from the repository files.');
  if (keys[0]) out.push(`- Where to start reading: ${code(keys[0].path)} (${safeText(keys[0].reason, 120)}).`);
  if (core[0]) out.push(`- Most depended-on file: ${code(core[0].path)}, imported by ${core[0].meta.fanIn} files, so a change there reaches the most code.`);
  out.push(`- Tests: ${testFiles} test file${testFiles === 1 ? '' : 's'}${core.length ? `; ${coreWithTests.length} of the ${core.length} most depended-on files have a matching test` : ''}.`);
  if (top[0]) out.push(`- Who changes it most: ${safeText(idx.personLabel(top[0][0]), 60)} (lead owner of ${top[0][1]} files).`);
  out.push('');

  out.push('## Getting started', '');
  if (o.runSteps.length === 0) out.push('No install, build or run commands could be derived from the repository files.', '');
  else {
    out.push('| Step | Command | Source |', '|---|---|---|');
    for (const s of o.runSteps) out.push(`| ${s.step} | ${code(safeText(s.command, 80))} | ${safeText(s.source, 100)}${s.inferred ? ' (usual command for this tooling, not read from a file)' : ''} |`);
    out.push('');
  }

  out.push('## Repository layout', '');
  out.push('| Folder | Files | Role |', '|---|---|---|');
  for (const f of layout) out.push(`| ${code(f.path)} | ${f.files} | ${safeText(f.role, 100)} |`);
  out.push('');

  out.push('## Entry points and execution flow', '');
  if (entries.length === 0) out.push('No file that starts on its own was detected, so this looks like a library. Its public surface is the barrel or index files listed under key files below.', '');
  else {
    out.push('Files that start running on their own, and the first file each one imports (follow that import to see where the work goes).', '');
    out.push('| Entry file | Why it counts as an entry | Imports first |', '|---|---|---|');
    for (const e of entries) {
      const next = firstChain(idx, e.path)[1];
      const why = `${safeText(e.kind, 20)}: ${e.reasons.map((r) => safeText(r, 60)).join('; ')}${e.command ? `. Run with ${code(safeText(e.command, 80))}` : ''}`;
      out.push(`| ${code(e.path)} | ${why} | ${next ? code(next.path) : 'nothing'} |`);
    }
    out.push('');
    const chain = firstChain(idx, entries[0].path);
    if (chain.length > 1) out.push(`Following the imports from ${code(entries[0].path)}: ${chain.map((c) => code(c.path)).join(' then ')}.`, '');
  }

  out.push('## Core modules', '');
  if (core.length === 0) out.push('There is no import graph for this repository (Tier 1 snapshot), so core modules cannot be ranked by how many files depend on them.', '');
  else {
    out.push('Ranked by how many files import them (more dependants means a change has a wider effect).', '', '| File | Imported by | Centrality |', '|---|---|---|');
    for (const f of core) out.push(`| ${code(f.path)} | ${f.meta.fanIn} files | ${(f.meta.centrality ?? 0).toFixed(2)} |`);
    out.push('');
  }

  out.push('## Data and configuration', '');
  const config = [...idx.files.values()].filter((f) => f.meta.isConfig).map((f) => f.path).slice(0, 10);
  const models = [...idx.files.values()].filter((f) => f.meta.tags?.includes('model') && !f.meta.isTest).map((f) => f.path).slice(0, 8);
  out.push(config.length ? `- Configuration files: ${config.map(code).join(', ')}` : '- No configuration files were detected.');
  if (models.length) out.push(`- Data models and database access: ${models.map(code).join(', ')}`);
  out.push('');

  out.push('## Testing', '');
  out.push(`- ${testFiles} test files in the snapshot.`);
  if (core.length) out.push(`- ${coreWithTests.length} of the ${core.length} core modules above have an associated test file${core.length - coreWithTests.length ? `; without tests: ${core.filter((f) => !(f.meta.testedBy ?? []).length).map((f) => code(f.path)).join(', ')}` : ''}.`);
  out.push('');

  out.push('## How changes usually flow', '');
  const co = idx.coChange.slice(0, 5);
  if (co.length) {
    out.push('Files that were changed together in 2 or more commits. If you edit one, check the other.', '');
    out.push('| File | Usually changes with | Commits together |', '|---|---|---|');
    for (const c of co) out.push(`| ${code(c.a)} | ${code(c.b)} | ${c.count} |`);
    out.push('');
  }
  const prs = idx.prs.slice(0, 5);
  if (prs.length) {
    out.push('Recent merged pull requests (titles are from GitHub and untrusted):', '');
    out.push('| PR | Title | Files touched |', '|---|---|---|');
    for (const p of prs) out.push(`| #${p.number} | ${safeText(p.title, 100)} | ${p.files.length} |`);
    out.push('');
  }
  if (!co.length && !prs.length) out.push('Not enough history in the snapshot to describe typical changes.', '');

  out.push('## Ownership', '');
  if (top.length) {
    out.push('People who most often changed the most files recently (from commit authors, recency weighted). Ask them before large changes.', '');
    out.push('| Person | Files they lead |', '|---|---|');
    for (const [id, n] of top) out.push(`| ${safeText(idx.personLabel(id), 60)} | ${n} |`);
    out.push('');
  } else out.push('No ownership data in the snapshot.', '');

  out.push('## Key files to read first', '');
  if (keys.length) {
    out.push('Read these in order. Each one is listed with the reason it matters.', '');
    out.push('| # | File | Why read it |', '|---|---|---|');
    keys.forEach((k, n) => out.push(`| ${n + 1} | ${code(k.path)} | ${safeText(k.reason, 160)} |`));
    out.push('');
  }

  out.push('## Limits of this draft', '');
  for (const n of lim.notes) out.push(`- ${safeText(n, 200)}`);
  out.push('- Folder roles and run commands marked as usual are inferred; confirm them against the maintainers.', '');
  return out.join('\n');
}

export interface Preview {
  title: string;
  sections: string[];
  excerpt: string;
  lines: number;
  characters: number;
}

/** The preview carries the whole draft (drafts are about a hundred lines), up to this many lines, so the person can review everything before confirming. */
export const PREVIEW_MAX_LINES = 400;

export function previewOf(markdown: string, excerptLines = PREVIEW_MAX_LINES): Preview {
  const lines = markdown.split('\n');
  return {
    title: lines[0].replace(/^#\s+/, ''),
    sections: lines.filter((l) => l.startsWith('## ')).map((l) => l.slice(3)),
    excerpt: lines.slice(0, excerptLines).join('\n'),
    lines: lines.length,
    characters: markdown.length,
  };
}

// --- Confirm token --------------------------------------------------------------------

export const draftHash = (markdown: string): string => createHash('sha256').update(markdown).digest('hex');

function mac(secret: string, snapshotId: string, hash: string, expiry: number): string {
  return createHmac('sha256', secret).update(`${snapshotId}|${hash}|${expiry}`).digest('base64url');
}

export function signToken(secret: string, snapshotId: string, hash: string, nowMs: number): { token: string; expiresAt: string } {
  const expiry = nowMs + TOKEN_TTL_MS;
  return { token: `${expiry}.${mac(secret, snapshotId, hash, expiry)}`, expiresAt: new Date(expiry).toISOString() };
}

export type TokenCheck = { ok: true } | { ok: false; reason: 'malformed' | 'expired' | 'invalid' };

export function verifyToken(secret: string, snapshotId: string, hash: string, token: string, nowMs: number): TokenCheck {
  const m = /^(\d{10,16})\.([A-Za-z0-9_-]{43})$/.exec(token.trim());
  if (!m) return { ok: false, reason: 'malformed' };
  const expiry = Number(m[1]);
  const expected = Buffer.from(mac(secret, snapshotId, hash, expiry));
  const given = Buffer.from(m[2]);
  // Check the signature first so an attacker learns nothing about expiry without a valid one.
  if (expected.length !== given.length || !timingSafeEqual(expected, given)) return { ok: false, reason: 'invalid' };
  if (nowMs > expiry) return { ok: false, reason: 'expired' };
  return { ok: true };
}
